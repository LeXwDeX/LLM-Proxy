"use strict";
// Gate for the shared table component: every data table in the admin UI sorts through core.createTableSort.
// Each header cell is either sortable (data-sort="key", with a getter registered under that key) or
// deliberately not (data-sort-none: the actions column, an expand toggle, a blank cell). A table that
// adds a column and forgets one of the two fails here instead of silently shipping an unsortable header.
const assert = require("node:assert/strict");
const test = require("node:test");
const { assembleAdminHTML } = require("../../../scripts/testing/assemble_admin_html.cjs");
const { manifest } = require("../../../scripts/testing/admin_ui_scripts.cjs");
const { createHarness, schemaFixture } = require("../../../scripts/testing/admin_ui_test.cjs");

const html = assembleAdminHTML();
// Script sources without comments (a comment may mention <thead>); newlines are kept so line numbers hold.
const blank = (text) => text.replace(/[^\n]/g, " ");
const scripts = manifest(html).map((script) => ({
  ...script,
  source: script.source.replace(/\/\*[\s\S]*?\*\//g, blank).replace(/^[ \t]*\/\/.*$/gm, blank),
}));

const THEAD = /<thead\b([^>]*)>([\s\S]*?)<\/thead>/gi;
const TH = /<th\b[^>]*>/gi;
const attr = (tag, name) => new RegExp("[\\s\"']" + name + "(?:=|[\\s>/])", "i").test(tag);
const sortAttrs = (tag) => ({ sort: attr(tag, "data-sort"), none: attr(tag, "data-sort-none") });

// Header cells that declare neither (or both) of data-sort / data-sort-none, from a markup fragment.
function undeclared(markup) {
  const bad = [];
  for (const [tag] of markup.matchAll(TH)) {
    const { sort, none } = sortAttrs(tag);
    if (sort === none) bad.push(tag);
  }
  return bad;
}
function staticHeads() {
  return [...html.matchAll(THEAD)].map((m) => ({ open: m[1], body: m[2], id: (/\bid="([^"]*)"/.exec(m[1]) || [])[1] || "" }));
}
// The assembled page carries scripts and styles; only the markup before them has tables.
const line = (text, index) => text.slice(0, index).split("\n").length;

test("every header cell of a static table declares data-sort or data-sort-none", () => {
  const heads = staticHeads();
  assert.ok(heads.length >= 17, "the page's tables are found (" + heads.length + " static <thead>)");
  const violations = [];
  let cells = 0;
  for (const head of heads) {
    cells += [...head.body.matchAll(TH)].length;
    for (const tag of undeclared(head.body)) violations.push((head.id || "(no id)") + ": " + tag);
  }
  assert.ok(cells >= 90, "header cells are found (" + cells + ")");
  assert.deepEqual(violations, [], "each <th> needs data-sort=\"key\" or data-sort-none, never both or neither");
});

test("a static sortable <thead> has an id for the sorter to bind", () => {
  const unnamed = staticHeads().filter((head) => /data-sort=/.test(head.body) && !head.id);
  assert.deepEqual(unnamed.map((head) => head.body.slice(0, 80)), []);
});

test("every table has a <thead>, so the header rule cannot be bypassed", () => {
  const withoutHead = [];
  for (const m of html.matchAll(/<table\b/gi)) {
    const rest = html.slice(m.index);
    const before = rest.slice(0, rest.search(/<tbody\b|<\/table>/i));
    if (!/<thead\b/i.test(before)) withoutHead.push("line " + line(html, m.index));
  }
  assert.deepEqual(withoutHead, []);
  for (const script of scripts) {
    for (const m of script.source.matchAll(/<table\b/gi)) {
      const rest = script.source.slice(m.index);
      const before = rest.slice(0, rest.search(/<tbody\b|<\/table>/i));
      if (!/<thead\b/i.test(before)) withoutHead.push(script.rel + ":" + line(script.source, m.index));
    }
  }
  assert.deepEqual(withoutHead, [], "generated tables need a <thead> too");
});

test("header cells generated by scripts declare data-sort or data-sort-none", () => {
  const violations = [];
  let spans = 0;
  for (const script of scripts) {
    const source = script.source;
    // Tables built as strings: everything between <thead and </thead>, including the concatenated expressions.
    for (const m of source.matchAll(/<thead\b/gi)) {
      const end = source.indexOf("</thead>", m.index);
      assert.ok(end > 0, script.rel + ":" + line(source, m.index) + " has an unterminated <thead>");
      spans++;
      for (const tag of undeclared(source.slice(m.index, end))) violations.push(script.rel + ":" + line(source, m.index) + " " + tag);
    }
    // Static <thead id="...TableHead"> elements whose cells a script fills in: head.innerHTML = "<tr><th ...".
    // The assigned expression runs until the next element lookup or the end of the enclosing function.
    for (const m of source.matchAll(/getElementById\(\s*"(\w+TableHead)"\s*\)\s*\.innerHTML\s*=/g)) {
      const rest = source.slice(m.index + m[0].length);
      const stop = rest.search(/getElementById\(|\n  \}\n/);
      spans++;
      for (const tag of undeclared(stop < 0 ? rest : rest.slice(0, stop))) violations.push(script.rel + ":" + line(source, m.index) + " " + m[1] + " " + tag);
    }
  }
  assert.ok(spans >= 5, "the generated headers are found (" + spans + ")");
  assert.deepEqual(violations, []);
});

// ---- runtime: render the generated headers and check them against the sorters that own them ----

function cellsOf(markup) {
  return [...markup.matchAll(TH)].map(([tag]) => ({ tag, key: (/data-sort=["']([^"']*)["']/.exec(tag) || [])[1] }));
}
const staticKeys = (id) => {
  const head = staticHeads().find((h) => h.id === id);
  return head ? cellsOf(head.body).filter((c) => c.key !== undefined).map((c) => c.key) : [];
};
const domKeys = (element) =>
  element.querySelectorAll("th[data-sort]").map((th) => th.getAttribute("data-sort"));

async function boot() {
  const harness = createHarness({ schema: schemaFixture() });
  const app = await harness.run();
  return { harness, app, sorters: Array.from(app.modules.core.listTableSorts()) };
}

test("generated headers carry data-sort / data-sort-none once rendered", async () => {
  const { harness, app } = await boot();
  const rendered = [];
  for (const id of ["quotaSummaryTableHead", "jobLevelTableHead"]) {
    const head = harness.ids.get(id);
    assert.ok(head.innerHTML.includes("<th"), id + " is generated at startup");
    rendered.push([id, head.innerHTML]);
  }
  rendered.push(["adminSchemaSummary", harness.ids.get("adminSchemaSummary").innerHTML]);
  // The per-group table inside an expanded quota row is generated with the rows.
  rendered.push(["quotaConvertedDetail", app.modules.quota.quotaConvertedDetail({ groups: { g1: { quotas: { daily: { used: 1, limit: 2 } } } } })]);
  for (const [name, markup] of rendered) {
    assert.ok(/<th\b/.test(markup), name + " has header cells");
    assert.deepEqual(undeclared(markup.replace(/<tbody[\s\S]*<\/tbody>/g, "")), [], name);
  }
});

test("every sortable header belongs to a sorter and every key has a getter", async () => {
  const { harness, sorters } = await boot();
  const bound = new Set();
  const problems = [];
  for (const sorter of sorters) {
    const columns = new Set(Array.from(sorter.keys()));
    const seen = new Set();
    let table = false;
    for (const head of sorter.heads()) {
      const isHead = head.tagName === "THEAD";
      table = table || isHead;
      if (head.id) bound.add(head.id);
      const keys = [...staticKeys(head.id), ...(typeof head.querySelectorAll === "function" ? domKeys(head) : [])];
      for (const key of keys) {
        seen.add(key);
        if (!columns.has(key)) problems.push((head.id || head.tagName) + ": header \"" + key + "\" has no getter");
      }
    }
    // A sorter bound to a <thead> owns that header: no getter may be left without a header cell. (A sorter on
    // a container, such as an expanded detail table, only sees its headers once they are rendered.)
    if (table && [...sorter.heads()].every((head) => head.tagName === "THEAD"))
      for (const key of columns) if (!seen.has(key)) problems.push(sorter.heads().map((h) => h.id).join(",") + ": getter \"" + key + "\" has no header cell");
  }
  assert.deepEqual(problems, []);
  // Every static header that sorts, or is filled in by a script, has a sorter.
  const unbound = staticHeads()
    .filter((head) => head.id && (/data-sort=/.test(head.body) || !/<th\b/.test(head.body)))
    .filter((head) => !bound.has(head.id))
    .map((head) => head.id);
  assert.deepEqual(unbound, [], "sortable headers must be bound to a createTableSort instance");
  assert.ok(harness.ids.size > 100);
});

